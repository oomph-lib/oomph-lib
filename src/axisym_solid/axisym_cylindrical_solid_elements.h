  //===========================================================================
  /// An Element that solves the axisymmetric solid mechanics equations,
  /// based on the principle of virtual displacements in cylindrical polar
  /// coordinates, using SolidTElements for the interpolation of the
  /// variable positions.
  //============================================================================
  template<unsigned NNODE_1D>
  class TAxisymCylindricalPVDElement
    : public virtual SolidTElement<2, NNODE_1D>,
      public virtual AxisymmetricCylindricalPVDEquations,
      public virtual ElementWithZ2ErrorEstimator
  {
  public:
    /// Constructor, there are no internal data points
    TAxisymCylindricalPVDElement()
      : SolidTElement<2, NNODE_1D>(), AxisymmetricCylindricalPVDEquations()
    {
    }

    /// Output function
    void output(std::ostream& outfile)
    {
      AxisymmetricCylindricalPVDEquations::output(outfile);
    }

    /// Output function
    void output(std::ostream& outfile, const unsigned& n_plot)
    {
      AxisymmetricCylindricalPVDEquations::output(outfile, n_plot);
    }


    /// C-style output function
    void output(FILE* file_pt)
    {
      AxisymmetricCylindricalPVDEquations::output(file_pt);
    }

    /// C-style output function
    void output(FILE* file_pt, const unsigned& n_plot)
    {
      AxisymmetricCylindricalPVDEquations::output(file_pt, n_plot);
    }

    /// Order of recovery shape functions for Z2 error estimation:
    /// Same order as shape functions.
    unsigned nrecovery_order()
    {
      return (NNODE_1D - 1);
    }

    /// Number of vertex nodes in the element
    unsigned nvertex_node() const
    {
      return TElement<2, NNODE_1D>::nvertex_node();
    }

    /// Pointer to the j-th vertex node in the element
    Node* vertex_node_pt(const unsigned& j) const
    {
      return TElement<2, NNODE_1D>::vertex_node_pt(j);
    }

    /// Function to describe the local dofs of the element. The ostream
    /// specifies the output stream to which the description
    /// is written; the string stores the currently
    /// assembled output that is ultimately written to the
    /// output stream by Data::desribe_dofs(...); it is typically
    /// built up incrementally as we descend through the
    /// call hierarchy of this function when called from
    /// Problem::describe_dofs(...)
    using SolidFiniteElement::describe_local_dofs;

    /// Number of 'flux' terms for Z2 error estimation
    unsigned num_Z2_flux_terms()
    {
      // Six flux terms
      return 6;
    }

    /// Get 'flux' for Z2 error recovery:   Upper triangular entries
    /// in strain tensor.
    void get_Z2_flux(const Vector<double>& s, Vector<double>& flux)
    {
#ifdef PARANOID
      unsigned num_entries = 6;
      if (flux.size() != num_entries)
      {
        std::ostringstream error_message;
        error_message << "The flux vector has the wrong number of entries, "
                      << flux.size() << ", whereas it should be " << num_entries
                      << std::endl;
        throw OomphLibError(error_message.str(),
                            OOMPH_CURRENT_FUNCTION,
                            OOMPH_EXCEPTION_LOCATION);
      }
#endif

      // Get strain matrix
      DenseMatrix<double> strain(3);
      this->get_strain(s, strain);

      // Pack into flux Vector
      unsigned icount = 0;

      // Start with diagonal terms
      for (unsigned i = 0; i < 3; i++)
      {
        flux[icount] = strain(i, i);
        icount++;
      }
      // Off diagonals row by row
      for (unsigned i = 0; i < 3; i++)
      {
        for (unsigned j = i + 1; j < 3; j++)
        {
          flux[icount] = strain(i, j);
          icount++;
        }
      }
    }
  };


